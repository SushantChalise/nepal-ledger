# ── 2. Failure paths ───────────────────────────────────────────────────────────


def test_missing_file_returns_failure(tmp_path: pathlib.Path) -> None:
    """parse() on a non-existent file must return status='failure'."""
    result = parse(str(tmp_path / "no-such-file.xlsx"), "doc-001")
    assert result.status == "failure"
    assert result.parser_version == PARSER_VERSION
    assert result.staging_rows == []
    assert len(result.errors) == 1
    assert result.errors[0].error_class == "Other"
    assert "not found" in result.errors[0].error_detail


def test_invalid_file_returns_failure(tmp_path: pathlib.Path) -> None:
    """parse() on a non-XLSX (e.g. HTML) file must return status='failure'."""
    bad_file = tmp_path / "knomad-bilateral-2024.xlsx"
    bad_file.write_bytes(b"<html>not an xlsx</html>")
    result = parse(str(bad_file), "doc-002")
    assert result.status == "failure"
    assert result.errors[0].error_class == "EncodingError"


def _make_xlsx_no_nepal(tmp_path: pathlib.Path) -> pathlib.Path:
    """Create a workbook with a 'Bilateral_Remittance' sheet that has no Nepal column."""
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Bilateral_Remittance"  # type: ignore[union-attr]
    ws.append([None, "China", "India", "USA"])  # type: ignore[union-attr]
    ws.append(["India", 100.0, None, 50.0])  # type: ignore[union-attr]
    path = tmp_path / "knomad-bilateral-2024.xlsx"
    buf = io.BytesIO()
    wb.save(buf)
    path.write_bytes(buf.getvalue())
    return path


def test_no_nepal_column_returns_failure(tmp_path: pathlib.Path) -> None:
    """parse() must return status='failure' with ColumnMissing when Nepal column absent."""
