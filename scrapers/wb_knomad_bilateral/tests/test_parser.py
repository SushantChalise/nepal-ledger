# ── 4. Year inference fallback ────────────────────────────────────────────────


def _make_xlsx_no_year_in_name(tmp_path: pathlib.Path) -> pathlib.Path:
    """Workbook with a bilateral sheet but no year in filename — should fail period inference."""
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Bilateral_Remittance"  # type: ignore[union-attr]
    ws.append([None, "Nepal"])  # type: ignore[union-attr]
    ws.append(["India", 1000.0])  # type: ignore[union-attr]
    path = tmp_path / "knomad-bilateral-data.xlsx"  # no year
    buf = io.BytesIO()
    wb.save(buf)
    path.write_bytes(buf.getvalue())
    return path


def test_no_year_in_filename_returns_failure(tmp_path: pathlib.Path) -> None:
    """parse() must fail with PeriodAmbiguous when year cannot be inferred."""
    path = _make_xlsx_no_year_in_name(tmp_path)
    result = parse(str(path), "doc-year-001")
    assert result.status == "failure"
    assert result.errors[0].error_class == "PeriodAmbiguous"


def _make_xlsx_year_in_sheet(tmp_path: pathlib.Path, year: int = 2023) -> pathlib.Path:
    """Workbook where year appears in cell A1, not the filename."""
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Bilateral_Remittance"  # type: ignore[union-attr]
    # Row 0: year mention in first cell, then Nepal header
    ws.append([f"Bilateral Remittance Matrix {year}", "Nepal"])  # type: ignore[union-attr]
    ws.append(["India", 900.0])  # type: ignore[union-attr]
    path = tmp_path / "knomad-bilateral-data.xlsx"  # no year in filename
    buf = io.BytesIO()
    wb.save(buf)
    path.write_bytes(buf.getvalue())
    return path


def test_year_inferred_from_sheet_content(tmp_path: pathlib.Path) -> None:
    """parse() should infer year from sheet header cell when filename has no year."""
    path = _make_xlsx_year_in_sheet(tmp_path, year=2023)
    result = parse(str(path), "doc-year-002")
    # Year found in sheet → no PeriodAmbiguous; should succeed or partial
    assert result.status in ("success", "partial")
    assert result.staging_rows[0].fiscal_year_bs == "2080/81"


# ── 5. Real fixture tests (skipped if file not present) ───────────────────

REAL_FIXTURE_2021 = (
    pathlib.Path(__file__).resolve().parent
    / "fixtures"
    / "bilateral_remittance_matrix_2021.xlsx"
)


@pytest.mark.skipif(
    not REAL_FIXTURE_2021.exists(),
    reason="real KNOMAD 2021 fixture not downloaded (run archive.org recovery)",
)
def test_real_fixture_2021_success() -> None:
    """Parser must return success against the real 2021 KNOMAD matrix."""
    res = parse(str(REAL_FIXTURE_2021), "real-2021")
    assert res.status == "success", f"Expected success, got {res.status}: {res.errors}"
    assert res.parser_version == PARSER_VERSION
    assert len(res.errors) == 0


@pytest.mark.skipif(
    not REAL_FIXTURE_2021.exists(),
    reason="real KNOMAD 2021 fixture not downloaded",
)
def test_real_fixture_2021_nepal_india_value() -> None:
    """India corridor value from real 2021 matrix must be > 1000 USD million.

    Verified against raw cell value in the KNOMAD Dec-2022 release:
    India -> Nepal = 1583.40 USD million (CY2021).
    """
    res = parse(str(REAL_FIXTURE_2021), "real-2021")
    india = next(
        (r for r in res.staging_rows if r.indicator_slug_raw == "knomad-remittance-to-nepal-from-india-annual"),
        None,
    )
    assert india is not None, "India corridor not found in real 2021 fixture"
    assert india.value == pytest.approx(1583.40, rel=0.01), (
        f"India->Nepal 2021 value {india.value} outside expected range"
    )
    assert india.unit == "usd_million"


@pytest.mark.skipif(
    not REAL_FIXTURE_2021.exists(),
    reason="real KNOMAD 2021 fixture not downloaded",
)
def test_real_fixture_2021_total_plausible() -> None:
    """World-row total (Nepal inflows) from CY2021 must be in [5000, 12000] USD million."""
    res = parse(str(REAL_FIXTURE_2021), "real-2021")
